// scripts/test-work-log.mjs — guards src/lib/work-log.ts (Home → Today:
// pasted Claude Code reports sorted into done / NEED / ideas). Compiles the
// lib on its own, like test-carry.mjs. Run: node scripts/test-work-log.mjs

import { execSync } from 'node:child_process'
import { mkdtempSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const out = mkdtempSync(join(tmpdir(), 'worklog-test-'))
execSync(
  'npx tsc src/lib/work-log.ts --outDir ' + out +
  ' --target es2020 --module esnext --moduleResolution bundler --skipLibCheck',
  { stdio: 'inherit' },
)
const { parseWorkLog, parseChat, cleanLine, classifyHeading } = await import(pathToFileURL(join(out, 'work-log.js')).href)

let pass = 0, fail = 0
const is = (label, got, want) => {
  if (JSON.stringify(got) === JSON.stringify(want)) { pass++; return }
  fail++; console.log('✗', label, '— got', JSON.stringify(got), 'want', JSON.stringify(want))
}

// A typical report: title, what was fixed, a NEED block, ideas, footer.
const report = `Brand hunt: BevNET sources
**What I fixed**
- Hunt searches **BevNET** first
- Added \`HUNT_SOURCES\` ([commit](https://github.com/x/y/commit/1))

**NEED: Paste REPORT_TOKEN in Vercel**
1. Open Vercel → Settings → Env
2. Add REPORT_TOKEN

Ideas for next time:
- Score finds by funding

---
_Generated by [Claude Code](https://claude.ai/code)_`

const chats = parseWorkLog(report)
is('footer is not a chat', chats.length, 1)
const c = chats[0]
is('title', c.title, 'Brand hunt: BevNET sources')
is('done', c.done, ['Hunt searches BevNET first', 'Added HUNT_SOURCES (commit (https://github.com/x/y/commit/1))'])
is('need label', c.needs.map(n => n.label), ['Paste REPORT_TOKEN in Vercel'])
is('need steps', c.needs[0].steps, ['Open Vercel → Settings → Env', 'Add REPORT_TOKEN'])
is('ideas', c.ideas, ['Score finds by funding'])

// Several chats in one paste.
const many = parseWorkLog('Chat A\n- did one\n===\nChat B\n- did two\n---\n\n')
is('two chats', many.map(x => x.title), ['Chat A', 'Chat B'])
is('two chats done', many.map(x => x.done), [['did one'], ['did two']])

// A generic need heading: each bullet is its own need.
const g = parseChat('**What you need to do**\n- Approve the Schedule\n- Pick LinkedIn pages')
is('generic need bullets', g.needs.map(n => n.label), ['Approve the Schedule', 'Pick LinkedIn pages'])
is('generic need title falls back to first need', g.title, 'Approve the Schedule')

// "we need to" in a sentence is not a NEED block.
const s = parseChat('Fixed the board\n- we need to keep the cap at 30')
is('lowercase need stays done', [s.needs.length, s.done], [0, ['we need to keep the cap at 30']])

// Untitled chat starting with a section heading: title from the first done line.
is('title from done', parseChat('## What I did\n- Cleaned up Home').title, 'Cleaned up Home')
is('empty paste', parseWorkLog('  \n---\n '), [])

is('clean link same text', cleanLine('[https://a.b](https://a.b)'), 'https://a.b')
is('heading kinds', ['What Leo needs', 'Next steps', 'Changes'].map(classifyHeading), ['need', 'idea', 'done'])
is('raw kept', c.raw.startsWith('Brand hunt'), true)

// The debriefs Leo pastes: no --- between them, "# Debrief:" / "DEBRIEF —"
// starts, ALL-CAPS headings, a "Here's a debrief" line, one pasted twice.
const leo = `# Debrief: LinkedIn tool (Sep 27)
## Built
- Run reports
## Known gaps / ideas not done
- Runs stall when hidden
Here's a debrief you can paste:
DEBRIEF — "brand finder bot" session (Oct 5)
WHAT I DID
- Mapped the hunt
STILL OPEN — LEO
1. Update Zach's SB Log token
2. Pick hunt cadence
4) DATA FIX (Leo approved)
- Moved 3 people
# Debrief: LinkedIn tool (Sep 27)
## Built
- Run reports
## Known gaps / ideas not done
- Runs stall when hidden`
const lc = parseWorkLog(leo)
is('debriefs split, duplicate dropped', lc.map(x => x.title), ['LinkedIn tool (Sep 27)', '"brand finder bot" session (Oct 5)'])
is('debrief 1 piles', [lc[0].done, lc[0].ideas], [['Run reports'], ['Runs stall when hidden']])
is('caps headings', [lc[1].done, lc[1].needs.map(n => n.label)], [['Mapped the hunt', 'Moved 3 people'], ['Update Zach\'s SB Log token', 'Pick hunt cadence']])

console.log(`${pass} passed, ${fail} failed`)
process.exit(fail ? 1 : 0)
